"""Explicit contract for every mounted method and route.

Object resolution and permission enforcement live in authz and the route dependencies.
Conditional policies describe request-specific checks that are evaluated by the handler.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class RoutePolicy:
    kind: str
    permissions: tuple[str, ...] = ()
    scoped: bool = True
    object_kind: str = ""
    action: str = ""
    parameter: str = ""
    any_of: tuple[str, ...] = ()
    condition: str = ""


def authenticated(*permissions, **options):
    return RoutePolicy("authenticated", permissions, **options)


def object_policy(kind, action, parameter, *permissions, **options):
    return RoutePolicy("object", permissions, object_kind=kind, action=action, parameter=parameter, **options)


