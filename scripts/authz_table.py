#!/usr/bin/env python3
"""Regenerate the route authorization reference."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from logentra_server.route_policies import ROUTE_POLICIES

DESTINATION = ROOT / "docs/v0.7/permissions.md"
CONDITIONS = {
    "catalog_fields": "permissions depend on the catalog sections submitted",
    "category_site": "global categories require unscoped access",
    "document_links": "read permission and access for each linked object",
    "optional_equipment_creation": "equipment.write when creating missing equipment",
    "qr_login_page": "anonymous login page, quick-entry data requires scoped readings.read and readings.write",
    "password_change": "browser session and current password",
    "self_or_manage": "own user or unscoped users.manage",
    "table_import": "equipment.write for equipment imports or missing asset creation, unscoped for equipment imports",
    "user_session": "browser user session required",
    "work_order_fields": "assignment requires workorders.assign, closing requires workorders.close",
}


def render():
    lines = [
        "# Route permissions",
        "",
        "Generated by `python scripts/authz_table.py`.",
        "",
        "Scoped access limits object and list results to the caller's assigned site and area.",
        "Object policies also check linked evidence, handover leads, and ownership where applicable.",
        "`/static` represents the static asset mount. Phone login and logout require the existing CSRF checks.",
        "",
        "| Method | Route | Policy | Requirements |",
        "| --- | --- | --- | --- |",
    ]
    for (method, path), policy in sorted(ROUTE_POLICIES.items(), key=lambda row: (row[0][1], row[0][0])):
        details = []
        if policy.object_kind:
            details.append(f"`{policy.object_kind}.{policy.action}`")
        if policy.permissions:
            details.append(" and ".join(f"`{permission}`" for permission in policy.permissions))
        if policy.any_of:
            details.append(" or ".join(f"`{permission}`" for permission in policy.any_of))
        if policy.kind != "public":
            details.append("scoped" if policy.scoped else "unscoped")
        if policy.condition:
            details.append(CONDITIONS[policy.condition])
        lines.append(f"| {method} | `{path}` | {policy.kind} | {', '.join(details)} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    DESTINATION.write_text(render(), encoding="utf-8")
